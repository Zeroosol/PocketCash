// Writes ios/Shared/Models+xtool.swift: the @Model classes from ios/Shared/Models.swift with SwiftData's macro
// expansion written out, for the SwiftPM / xtool build (xtool has no SwiftData macro plugin). It uses only
// SwiftData's public API (PersistentModel, BackingData, Schema.PropertyMetadata), the same calls the real macro
// generates. Adapted from Splitty's tool. Run through tools/xtool_prepare.js. No dependencies.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'ios/Shared/Models.swift');
const OUT = path.join(ROOT, 'ios/Shared/Models+xtool.swift');

// `    @Attribute(.unique) var id: UUID`, `    var name: String`, `    @Relationship(...) var transactions: [X] = []`
const STORED = /^(\s+)(?:@(Attribute|Relationship)\((.*)\)\s+)?var (\w+): ([^={]+?)(?:\s*=\s*(.+?))?\s*$/;

function expandClass(name, body) {
  const props = [];
  const out = [];
  for (const line of body) {
    const m = STORED.exec(line);
    if (!m || line.trimEnd().endsWith('{')) { out.push(line); continue; }
    const [, ind, kind, args, prop, type, def] = m;
    props.push({ prop, kind, args, def });
    const i2 = ind + '    ', i3 = i2 + '    ';
    out.push(
      `${ind}var ${prop}: ${type.trim()}${def ? ` = ${def}` : ''} {`,
      `${i2}@storageRestrictions(accesses: _$backingData, initializes: _${prop})`,
      `${i2}init(initialValue) {`,
      `${i3}_$backingData.setValue(forKey: \\.${prop}, to: initialValue)`,
      `${i3}_${prop} = _SwiftDataNoType()`,
      `${i2}}`,
      `${i2}get {`,
      `${i3}_$observationRegistrar.access(self, keyPath: \\.${prop})`,
      `${i3}return self.getValue(forKey: \\.${prop})`,
      `${i2}}`,
      `${i2}set {`,
      `${i3}_$observationRegistrar.withMutation(of: self, keyPath: \\.${prop}) {`,
      `${i3}    self.setValue(forKey: \\.${prop}, to: newValue)`,
      `${i3}}`,
      `${i2}}`,
      `${ind}}`,
      `${ind}private var _${prop}: _SwiftDataNoType`,
    );
  }
  const meta = props.map(({ prop, kind, args, def }) => {
    const metadata = kind === 'Attribute' ? `SwiftData.Schema.Attribute(${args})`
      : kind === 'Relationship' ? `SwiftData.Schema.Relationship(${args})` : 'nil';
    return `            SwiftData.Schema.PropertyMetadata(name: "${prop}", keypath: \\${name}.${prop}, defaultValue: ${def ?? 'nil'}, metadata: ${metadata}),`;
  });
  out.push(
    '',
    '    // MARK: Generated by @Model',
    '',
    `    private var _$backingData: any SwiftData.BackingData<${name}> = ${name}.createBackingData()`,
    `    public var persistentBackingData: any SwiftData.BackingData<${name}> {`,
    '        get { _$backingData }',
    '        set { _$backingData = newValue }',
    '    }',
    `    static var schemaMetadata: [SwiftData.Schema.PropertyMetadata] {`,
    '        [',
    ...meta,
    '        ]',
    '    }',
    `    required init(backingData: any SwiftData.BackingData<${name}>) {`,
    ...props.map(({ prop }) => `        _${prop} = _SwiftDataNoType()`),
    '        self.persistentBackingData = backingData',
    '    }',
    '    private let _$observationRegistrar = Observation.ObservationRegistrar()',
    '    struct _SwiftDataNoType {}',
  );
  return [`final class ${name} {`, ...out, '}', '',
    `extension ${name}: SwiftData.PersistentModel {}`,
    `extension ${name}: Observation.Observable {}`].join('\n');
}

function expandModels() {
  const lines = fs.readFileSync(SRC, 'utf8').split(/\r?\n/);
  const classes = [];
  for (let i = 0; i < lines.length; i++) {
    if (lines[i].trim() !== '@Model') continue;
    const head = /^final class (\w+) \{$/.exec(lines[i + 1] || '');
    if (!head) throw new Error(`Models.swift:${i + 2}: expected "final class Name {" after @Model`);
    const end = lines.indexOf('}', i + 2);
    if (end < 0) throw new Error(`Models.swift: no closing brace for ${head[1]}`);
    classes.push(expandClass(head[1], lines.slice(i + 2, end)));
    i = end;
  }
  if (!classes.length) throw new Error('Models.swift: no @Model classes found');
  const text = [
    '// Generated by tools/expand_models.js from Models.swift. Do not edit: change Models.swift and run',
    '// `node tools/xtool_prepare.js`. Only the SwiftPM / xtool build compiles this; Xcode uses @Model directly.',
    '#if SWIFT_PACKAGE',
    'import SwiftData',
    'import Observation',
    'import Foundation',
    '',
    classes.join('\n\n'),
    '#endif',
    '',
  ].join('\n');
  fs.writeFileSync(OUT, text);
  console.log(`${path.relative(ROOT, OUT).split(path.sep).join('/')}: ${classes.length} models`);
}

module.exports = { expandModels };
if (require.main === module) expandModels();
